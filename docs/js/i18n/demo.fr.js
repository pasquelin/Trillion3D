export function localizeDemoText(text, locale) {
  if (locale !== 'fr' || typeof text !== 'string') return text;
  if (EXACT[text] ?? demoDetailsFr[text]) return EXACT[text] ?? demoDetailsFr[text];
  const singular = text.match(
    /^determinant (.+): sixteen zeros, like the reference — test the determinant, never the output$/,
  );
  if (singular)
    return `déterminant ${singular[1]} : seize zéros comme la référence ; testez le déterminant, jamais la sortie`;
  const canvas = text.match(/^(.+) \(y (.+)\)$/);
  if (canvas) return `${localizeDemoText(canvas[1], locale)} (y ${canvas[2]})`;
  return text;
}
