import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import prettier from 'prettier';
import { analyzeEntries, consumerImports, ENTRIES, ROOT } from './sdk-api-model.mjs';
import { DOCUMENTED_GAPS } from './sdk-api-documented.mjs';

const check = process.argv.includes('--check');
const rows = analyzeEntries();
const consumers = consumerImports();
rows.push(...DOCUMENTED_GAPS);

const CATEGORY_RULES = [
  ['llm', /\/llm\//],
  ['math', /\/math|\/projectionOracles|\/matrixOrientation|\/hiz/],
  ['lighting', /\/lighting|\/sceneLight|\/bounce|\/proxy/],
  ['diagnostics', /diagnostic|metrics|stats|stageProfile|competitors|oracles|compareImages|paths/],
  ['streaming', /manifest|page|geometryContracts|cacheContracts|texture/],
  ['lifecycle', /jobs|safety|events|contractsBase/],
];

function category(row) {
  return CATEGORY_RULES.find(([, pattern]) => pattern.test(row.module))?.[0] ?? 'contracts';
}

function classification(row) {
  return /oracles|competitors|compareImages|lightingExperiment|screenErrorVariant/.test(row.module)
    ? 'experimental'
    : 'public';
}

function environments(row) {
  if (row.entries.includes('core')) return 'common, browser, node, worker';
  if (row.entries.includes('browser')) return 'browser';
  return 'node';
}

function sourceFor(row, facade) {
  const depth = facade.includes('sdk-core/index') ? '../../' : '../';
  return `${depth}${row.module.slice('packages/'.length)}`;
}

async function write(path, content) {
  const absolute = join(ROOT, path);
  const prettierConfig = await prettier.resolveConfig(absolute);
  const formatted = await prettier.format(content, {
    ...prettierConfig,
    filepath: absolute,
  });
  mkdirSync(dirname(absolute), { recursive: true });
  if (check) {
    if (readFileSync(absolute, 'utf8') !== formatted) throw new Error(`${path} is stale`);
  } else writeFileSync(absolute, formatted);
}

function exportLines(selected, source) {
  const lines = ['// Generated by scripts/generate-sdk-facade.mjs.'];
  for (const module of [...new Set(selected.map((row) => sourceFor(row, source)))]) {
    const group = selected.filter((row) => sourceFor(row, source) === module);
    const values = group.filter((row) => row.kind !== 'type').map((row) => row.name);
    const types = group.filter((row) => row.kind === 'type').map((row) => row.name);
    if (values.length) lines.push(`export {\n  ${values.join(',\n  ')},\n} from '${module}';`);
    if (types.length) lines.push(`export type {\n  ${types.join(',\n  ')},\n} from '${module}';`);
  }
  return `${lines.join('\n')}\n`;
}

const common = rows.filter((row) => row.entries.includes('core'));
const categories = [...new Set(common.map(category))].sort();
for (const name of categories)
  await write(
    `packages/sdk/common/${name}.ts`,
    exportLines(
      common.filter((row) => category(row) === name),
      '../../sdk-core/index.ts',
    ),
  );
await write(
  'packages/sdk/common/index.ts',
  `${categories.map((name) => `export * from './${name}.ts';`).join('\n')}\n`,
);

const browserOnly = rows.filter(
  (row) => row.entries.includes('browser') && !row.entries.includes('core'),
);
await write(
  'packages/sdk/browser.ts',
  `export * from './common/index.ts';\n${exportLines(browserOnly, '../sdk-browser/index.ts')}`,
);
const nodeOnly = rows.filter(
  (row) => row.entries.includes('node') && !row.entries.includes('core'),
);
await write(
  'packages/sdk/node.mts',
  `export * from './common/index.ts';\n${exportLines(nodeOnly, '../sdk-node/index.mts')}`,
);
await write('packages/sdk/index.ts', "export * from './common/index.ts';\n");

const entryLabel = {
  core: 'web-geometry (common)',
  browser: 'web-geometry (browser condition)',
  node: 'web-geometry (node condition)',
};
const inventory = rows.map((row) => ({
  name: row.name,
  kind: row.kind,
  definingModule: row.module,
  currentEntryPoints: row.entries.map((entry) => entryLabel[entry]),
  proposedEnvironments: environments(row),
  classification: classification(row),
  affectedConsumers: [...(consumers.get(row.name) ?? []), ...(row.consumers ?? [])].sort(),
  disposition: row.disposition ?? 'retained',
  bindingIdentity: row.identity,
}));
const collisions = Object.entries(Object.groupBy(inventory, (entry) => entry.name))
  .filter(([, entries]) => new Set(entries.map((entry) => entry.bindingIdentity)).size > 1)
  .map(([name, entries]) => ({ name, bindings: entries.map((entry) => entry.bindingIdentity) }));
await write(
  'docs/api-inventory.json',
  `${JSON.stringify({ generatedFrom: ENTRIES, collisions, exports: inventory }, null, 2)}\n`,
);
