// Bundles the public surface the documentation runs — the common facade's maths, diagnostic,
// quality and format tables, and the internal browser depth convention — into one browser
// module, so every demo of the portal executes the engine itself rather than a copy of it.
import { build } from 'esbuild';
import { resolve } from 'node:path';

const ENTRY = [
  // The whole public maths: every demo calls the function its page documents, by its own name.
  `export * from './common/math.ts';`,
  // The tables the enum pages show, read from the engine rather than copied into the page.
  `export { DIAGNOSTICS } from './common/diagnostics.ts';`,
  `export { LOD_QUALITY, adaptivePixelError, lodQuality } from './common/contracts.ts';`,
  `export { COLUMN_KIND } from './common/streaming.ts';`,
  // The portal explains this internal convention but does not present it as an application import.
  `export { DEPTH_CLEAR, DEPTH_COMPARE_OR_EQUAL, DEPTH_NEAR } from '../sdk-browser/depthConvention.ts';`,
].join('\n');

/** Writes the demo bundle: browser ESM, minified, a header naming its source. */
export async function buildDemo(root, outfile) {
  await build({
    stdin: { contents: ENTRY, resolveDir: resolve(root, 'packages/sdk'), loader: 'ts' },
    outfile,
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    minify: true,
    banner: { js: '// Generated by pnpm build:docs from packages/ — do not edit.' },
    logLevel: 'silent',
  });
}
