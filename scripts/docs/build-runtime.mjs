/** Build only this repository's engine; Three remains an external peer dependency. */
import { build } from 'esbuild';
import { copyFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';

export async function buildRuntime(root, outdir) {
  await mkdir(outdir, { recursive: true });
  await build({
    absWorkingDir: root,
    entryPoints: {
      engine: 'packages/sdk-browser/index.ts',
      pageDecodeWorker: 'packages/sdk-browser/pageDecodeWorker.ts',
      pageIntegrationWorker: 'packages/sdk-browser/pageIntegrationWorker.ts',
    },
    outdir,
    bundle: true,
    minify: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    external: ['three', 'three/*'],
    supported: { 'template-literal': false },
    banner: {
      js: '// Generated by pnpm build:docs. Third-party engine dependencies remain external.',
    },
    logLevel: 'warning',
  });
  await copyFile(
    resolve(root, 'packages/sdk-browser/pageCodec.wasm'),
    resolve(outdir, 'pageCodec.wasm'),
  );
}
