// The GGX energy table built sample by sample (`shadingEnergy.ts` holds it as data, which the test of that file checks against this
// builder bit for bit). Run `node packages/sdk-core/src/lighting/shadingEnergy.fixture.ts` to write the data (`shadingEnergyTable.ts`).
import { writeFileSync } from 'node:fs'
import { TAU } from '../../../math/src/constants.ts'
import { owenSobolPoint } from '../../../math/src/sequence/owenSobol.ts'
import { SHADING_ENERGY_SIZE } from './shadingEnergy.ts'

/** Points of the sequence a texel is the mean of. */
export const SHADING_ENERGY_SAMPLES = 1 << 14
/** The least roughness a lobe is built with. */
const MIN_ROUGHNESS = 0.01

/**
 * The texel (`column`, `row`) of the table for the view cosine `noV` and the roughness `roughness`: `[E, Ef]`, the means over `samples`
 * points of the Owen-scrambled Sobol sequence of the texel (`owenSobolPoint`, the texel's place the pixel). The view lies in the xz
 * plane, the lobe round.
 */
export function shadingEnergyTexel(
  noV: number,
  roughness: number,
  column: number,
  row: number,
  samples = SHADING_ENERGY_SAMPLES,
): readonly [number, number] {
  const vz = Math.max(noV, 1e-8)
  const vx = Math.sqrt(Math.max(1 - vz * vz, 0))
  const alpha = Math.max(roughness, MIN_ROUGHNESS) ** 2
  // The view in the frame where the lobe is stretched to a hemisphere, and its length there.
  const lenV = Math.hypot(vx * alpha, vz)
  const stretchedX = (vx * alpha) / lenV
  const stretchedZ = vz / lenV
  // The range of normals the sampling keeps to those whose reflection can stay above the horizon (the bound k).
  const s2 = (1 + vx) ** 2
  const a2 = alpha * alpha
  const bound = (s2 - a2 * s2) / (s2 + a2 * vz * vz)
  let energy = 0
  let fresnelEnergy = 0
  for (let i = 0; i < samples; i++) {
    const [first, second] = owenSobolPoint(column, row, 0, i, samples)
    const phi = TAU * first
    const z = 1 + (-bound * stretchedZ - 1) * second
    const sine = Math.sqrt(Math.min(Math.max(1 - z * z, 0), 1))
    // The cap's point added to the stretched view, then unstretched.
    let hx = sine * Math.cos(phi) + stretchedX
    let hy = sine * Math.sin(phi)
    let hz = Math.max(0, z + stretchedZ)
    hx *= alpha
    hy *= alpha
    const hLength = Math.hypot(hx, hy, hz)
    hx /= hLength
    hy /= hLength
    hz /= hLength
    const vDotH = vx * hx + vz * hz
    const lx = 2 * vDotH * hx - vx
    const ly = 2 * vDotH * hy
    const lz = 2 * vDotH * hz - vz
    if (lz <= 0) continue
    const noL = Math.min(lz, 1)
    const lenL = Math.hypot(lx * alpha, ly * alpha, noL)
    const weight = (noL * (lenV + bound * vz)) / (vz * lenL + noL * lenV)
    energy += weight
    fresnelEnergy += weight * (1 - vDotH) ** 5
  }
  return [energy / samples, fresnelEnergy / samples]
}

/**
 * The whole table built: `SHADING_ENERGY_SIZE` rows of roughness (rising) of `SHADING_ENERGY_SIZE` columns of N·V (rising), a pair
 * `[E, Ef]` a texel, each at its centre.
 */
export function shadingEnergyTable(samples = SHADING_ENERGY_SAMPLES) {
  const table = new Float32Array(SHADING_ENERGY_SIZE * SHADING_ENERGY_SIZE * 2)
  for (let row = 0; row < SHADING_ENERGY_SIZE; row++)
    for (let column = 0; column < SHADING_ENERGY_SIZE; column++)
      table.set(
        shadingEnergyTexel(
          (column + 0.5) / SHADING_ENERGY_SIZE,
          (row + 0.5) / SHADING_ENERGY_SIZE,
          column,
          row,
          samples,
        ),
        (row * SHADING_ENERGY_SIZE + column) * 2,
      )
  return table
}

/** The source of the data module (`shadingEnergyTable.ts`) holding `table`. */
function shadingEnergyTableSource(table: Float32Array) {
  const lines: string[] = []
  for (let i = 0; i < table.length; i += 8)
    lines.push(`  ${Array.from(table.subarray(i, i + 8), (v) => String(v)).join(', ')},`)
  return `// Generated by \`node packages/sdk-core/src/lighting/shadingEnergy.fixture.ts\`: do not edit.
// The GGX energy table, row after row of roughness, column after column of N·V, a pair [E, Ef] a texel (\`shadingEnergy.ts\`).
export const SHADING_ENERGY_TABLE = new Float32Array([
${lines.join('\n')}
])
`
}

if (import.meta.main)
  writeFileSync(
    new URL('./shadingEnergyTable.ts', import.meta.url),
    shadingEnergyTableSource(shadingEnergyTable()),
  )
