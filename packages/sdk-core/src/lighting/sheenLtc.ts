export function sheenLtcHalves() {
  if (decoded) return decoded
  const text = atob(SHEEN_LTC_BASE64),
    halves = new Uint16Array(SHEEN_LTC_SIZE * SHEEN_LTC_SIZE * CHANNELS)
  for (let index = 0; index < halves.length; index++)
    halves[index] = text.charCodeAt(2 * index) | (text.charCodeAt(2 * index + 1) << 8)
  return (decoded = halves)
}

/**
 * The directional albedo of the lobe for a view along the normal: the `B` channel of the table's last row, one value for
 * each of the 32 columns, the square root of the roughness rising. The sampler at the texel centres of that row reads the
 * line between two neighbours: a fuzz roughness r gives the line's value at `sqrt(r) * 31`.
 */
export const SHEEN_LTC_ALBEDO_ALONG_NORMAL = Float32Array.from(
  { length: SHEEN_LTC_SIZE },
  (_, column) =>
    fromHalf(sheenLtcHalves()[((SHEEN_LTC_SIZE - 1) * SHEEN_LTC_SIZE + column) * CHANNELS + 2]),
)
